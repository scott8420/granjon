// embed -- a build-time helper: turn data files into one C++ source that
// granjon_core compiles in, so the bundled Unicode data (resources/ucd,
// resources/charsets) needs no file on disk at run time and no GLib
// resource API in the GTK-free core. (C++23 has no #embed in g++ 13.)
//
//   embed OUT.cpp  key=path  [key=path ...]
//
// Emits granjon::unicode::embedded::kFiles[] (key, data, size) in argument
// order, the data as string literals (octal escapes for anything that is
// not printable ASCII). Every literal is NUL-terminated by the compiler; size
// excludes that NUL.
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: embed OUT.cpp key=path [key=path ...]\n");
        return 2;
    }
    std::ostringstream o;
    o << "// Generated by tools/embed.cpp -- do not edit.\n"
         "#include \"unicode/Embedded.hpp\"\n\n"
         "namespace granjon::unicode::embedded {\nnamespace {\n";
    std::vector<std::pair<std::string, std::size_t>> files;
    for (int i = 2; i < argc; ++i) {
        const std::string arg = argv[i];
        const auto eq = arg.find('=');
        if (eq == std::string::npos) { std::fprintf(stderr, "embed: bad arg %s\n", argv[i]); return 2; }
        const std::string key = arg.substr(0, eq), path = arg.substr(eq + 1);
        std::ifstream in(path, std::ios::binary);
        if (!in) { std::fprintf(stderr, "embed: cannot read %s\n", path.c_str()); return 1; }
        std::string data((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        o << "const char d" << files.size() << "[] =\n\"";
        std::size_t col = 0;
        for (unsigned char c : data) {
            if (c == '\n') { o << "\\n\"\n\""; col = 0; continue; }
            if (c == '\\' || c == '"') o << '\\' << c;
            else if (c >= 0x20 && c < 0x7F && c != '?') o << c;   // '?' avoids trigraph noise
            else { char b[8]; std::snprintf(b, sizeof b, "\\%03o", c); o << b; }
            if (++col > 400) { o << "\"\n\""; col = 0; }
        }
        o << "\";\n";
        files.emplace_back(key, data.size());
    }
    o << "}  // namespace\n\nconst File kFiles[] = {\n";
    for (std::size_t i = 0; i < files.size(); ++i)
        o << "    {\"" << files[i].first << "\", d" << i << ", " << files[i].second << "},\n";
    o << "};\nconst std::size_t kFileCount = " << files.size() << ";\n\n"
         "}  // namespace granjon::unicode::embedded\n";

    std::ofstream out(argv[1], std::ios::binary);
    out << o.str();
    return out ? 0 : 1;
}
