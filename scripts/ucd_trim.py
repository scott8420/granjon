#!/usr/bin/env python3
"""ucd_trim.py -- regenerate Granjon's bundled Unicode data (resources/ucd,
resources/charsets) from the upstream files.

Run by hand when Unicode / AGL / a char set moves on; the output is checked
in, so a build never needs the network. CMake embeds the output into
granjon_core (tools/embed.cpp), so the core stays GTK- and GLib-free.

    scripts/ucd_trim.py RAW_DIR

RAW_DIR holds the upstream files:

  UnicodeData.txt, Blocks.txt   https://www.unicode.org/Public/17.0.0/ucd/
  glyphlist.txt, aglfn.txt      https://github.com/adobe-type-tools/agl-aglfn
  adobe-latin-2.txt, -3.txt     https://github.com/adobe-type-tools/adobe-latin-charsets
  GF_Latin_Core.nam             https://github.com/googlefonts/glyphsets
                                (data/results/nam/GF_Latin_Core.nam)
  wgl4.cps                      WGL4, one hex codepoint per line (from
                                https://www.alanwood.net/wgl4.html, which
                                tabulates Microsoft's WGL4.0 spec)

Writes, next to this script, into ../granjon/resources/:

  ucd/ucd.txt        CP;NAME;GC;DECOMP;UPPER;LOWER   one assigned codepoint
                     per line, empty fields kept; ranges as FIRST..LAST;
                     NAME-PREFIX;GC (CJK, Hangul, Tangut ... whose names are
                     algorithmic). <control> takes its Unicode 1 name.
  ucd/blocks.txt     FIRST..LAST;Block Name
  ucd/glyphlist.txt  AGL (name;hex[ hex...]), verbatim
  ucd/aglfn.txt      AGLFN (hex;name;CHARACTER NAME), verbatim
  charsets/*.txt     "# name:" / "# source:" header, then HEX  glyphname
"""
import os
import sys

UNICODE_VERSION = "17.0.0"


def main(raw):
    here = os.path.dirname(os.path.abspath(__file__))
    res = os.path.join(here, "..", "granjon", "resources")
    ucd_dir = os.path.join(res, "ucd")
    cs_dir = os.path.join(res, "charsets")
    os.makedirs(ucd_dir, exist_ok=True)
    os.makedirs(cs_dir, exist_ok=True)

    # ── UnicodeData -> ucd.txt ───────────────────────────────────────────────
    names = {}
    out = [f"# Granjon trimmed UCD {UNICODE_VERSION} -- generated by scripts/ucd_trim.py; do not edit.",
           "# CP;NAME;GC;DECOMP;UPPER;LOWER   or   FIRST..LAST;NAME-PREFIX;GC",
           "# Unicode data: Copyright (c) Unicode, Inc. Unicode License v3 (https://www.unicode.org/license.txt)"]
    pending = None
    with open(os.path.join(raw, "UnicodeData.txt"), encoding="utf-8") as f:
        for line in f:
            p = line.rstrip("\n").split(";")
            cp, name, gc, decomp, u1 = p[0], p[1], p[2], p[5], p[10]
            upper, lower = p[12], p[13]
            if name.endswith(", First>"):
                pending = (cp, name[1:-len(", First>")], gc)
                continue
            if name.endswith(", Last>"):
                first, label, g = pending
                pending = None
                prefix = {"CJK Ideograph": "CJK UNIFIED IDEOGRAPH-",
                          "Tangut Ideograph": "TANGUT IDEOGRAPH-",
                          "Hangul Syllable": "HANGUL SYLLABLE ",
                          }.get(label.split(" Extension")[0].split(" Supplement")[0], "")
                if not prefix and label.startswith("CJK Ideograph"):
                    prefix = "CJK UNIFIED IDEOGRAPH-"
                out.append(f"{first}..{cp};{prefix};{g}")
                continue
            if name == "<control>":
                name = u1 or "<control>"
            names[int(cp, 16)] = name
            out.append(f"{cp};{name};{gc};{decomp};{upper};{lower}")
    with open(os.path.join(ucd_dir, "ucd.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")

    # ── Blocks ───────────────────────────────────────────────────────────────
    blocks = [f"# Unicode {UNICODE_VERSION} blocks -- generated by scripts/ucd_trim.py; do not edit."]
    with open(os.path.join(raw, "Blocks.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.split("#")[0].strip()
            if line:
                rng, nm = [s.strip() for s in line.split(";")]
                blocks.append(f"{rng};{nm}")
    with open(os.path.join(ucd_dir, "blocks.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(blocks) + "\n")

    # ── AGL / AGLFN, verbatim (their license header rides along) ─────────────
    for fn in ("glyphlist.txt", "aglfn.txt"):
        with open(os.path.join(raw, fn), encoding="utf-8") as f:
            data = f.read()
        with open(os.path.join(ucd_dir, fn), "w", encoding="utf-8") as f:
            f.write(data)

    aglfn = {}
    for line in open(os.path.join(raw, "aglfn.txt"), encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        h, n, _ = line.strip().split(";")
        aglfn[int(h, 16)] = n

    def nice(cp):
        if cp in aglfn:
            return aglfn[cp]
        return f"uni{cp:04X}" if cp <= 0xFFFF else f"u{cp:05X}"

    def write_set(ident, title, source, cps):
        cps = sorted(set(cps))
        lines = [f"# name: {title}", f"# source: {source}",
                 f"# {len(cps)} characters -- generated by scripts/ucd_trim.py"]
        for cp in cps:
            lines.append(f"{cp:04X}  {nice(cp)}")
        with open(os.path.join(cs_dir, ident + ".txt"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print(f"  {ident}: {len(cps)}")

    # ── char sets ────────────────────────────────────────────────────────────
    write_set("latin-1", "Latin-1", "ISO 8859-1 printable: U+0020-007E, U+00A0-00FF",
              list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)))

    def adobe(fn):
        cps = []
        for line in open(os.path.join(raw, fn), encoding="utf-8"):
            h = line.split("\t")[0]
            if h != "Unicode" and h.strip():
                cps.append(int(h, 16))
        return cps
    write_set("adobe-latin-2", "Adobe Latin 2",
              "adobe-type-tools/adobe-latin-charsets (MIT)", adobe("adobe-latin-2.txt"))
    write_set("adobe-latin-3", "Adobe Latin 3",
              "adobe-type-tools/adobe-latin-charsets (MIT)", adobe("adobe-latin-3.txt"))

    gf = [int(l.split()[0], 16) for l in open(os.path.join(raw, "GF_Latin_Core.nam"), encoding="utf-8")
          if l.startswith("0x")]
    write_set("gf-latin-core", "GF Latin Core",
              "googlefonts/glyphsets, encoded glyphs only (Apache-2.0)", gf)

    # WGL4 without its two Private Use entries (U+F001 / F002, old Mac fi / fl
    # duplicates of U+FB01 / FB02), which a modern font should not map.
    wgl = [int(l, 16) for l in open(os.path.join(raw, "wgl4.cps")) if l.strip()]
    wgl = [c for c in wgl if not (0xE000 <= c <= 0xF8FF)]
    write_set("wgl4", "WGL4", "Microsoft WGL4.0, less its two Private Use code points", wgl)

    print(f"ucd.txt: {len(names)} named code points, {len(out) - 3 - len(names)} ranges")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
